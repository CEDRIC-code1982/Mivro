/**
 * @file ISessionShareService.ts
 * @description Abstract port for collaborative session sharing (F5).
 *
 *              Distinct from {@link IRealtimeService} (F4 live positions): this
 *              port manages the shared ROSTER (meta + members / start points) of
 *              a session, published to Firebase RTDB so guests can join via a
 *              `mivro://session/{id}` deep link.
 *
 *              Allows swapping the sharing backend without touching business
 *              logic nor presentation.
 *
 *              ⚠️ GDPR: the session expires (24h guest / 7d account); it is
 *              deleted at the end of the session; exact coordinates are never
 *              logged.
 *
 *              Implementations: FirebaseSessionShareService (infrastructure/).
 *
 * @module services/domain/sharing/ISessionShareService
 */

// [ADDED] F5 — ISessionShareService port + typed error
import type { Coordinates } from '@entities/Location';
import type {
  SharedSession,
  SharedSessionMember,
  SharedSessionOwnerType,
} from '@entities/SharedSession';

/**
 * Unsubscribe function returned by {@link ISessionShareService.subscribeToSharedSession}.
 */
export type SessionShareUnsubscribe = () => void;

/**
 * Callback invoked on every change of the shared session (meta + members).
 *
 * Receives the **validated** (Zod) session, or `null` if it no longer exists.
 *
 * @param session - Validated shared session or null
 */
export type SharedSessionUpdateHandler = (session: SharedSession | null) => void;

/**
 * Result of creating a shared session.
 */
export interface CreateSharedSessionResult {
  /** Shared session identifier */
  readonly sessionId: string;
  /** `mivro://session/{id}` deep link */
  readonly link: string;
  /** Expiration date (epoch ms) */
  readonly expiresAt: number;
}

/**
 * Member to add to the roster (without `memberId`, generated by caller/adapter).
 */
export type SharedSessionMemberInput = SharedSessionMember;

/**
 * Abstract port for the session sharing service.
 *
 * @example
 *   const { sessionId, link } = await shareService.createSharedSession(session, 'guest');
 *   const unsub = shareService.subscribeToSharedSession(sessionId, (shared) => render(shared));
 *   await shareService.joinSharedSession(sessionId, member);
 *   await shareService.updateMidpoint(sessionId, midpoint, radius);
 *   await shareService.removeMember(sessionId, memberId);
 *   await shareService.deleteSharedSession(sessionId);
 *   unsub();
 */
export interface ISessionShareService {
  /**
   * Publishes the current session to the shared backend (meta + members).
   *
   * @param session - Shared session to publish (meta + initial roster)
   * @param ownerType - Owner type (drives expiration)
   * @returns Identifier, deep link and expiration date
   * @throws {SessionShareError} If the publish fails
   */
  createSharedSession(
    session: SharedSession,
    ownerType: SharedSessionOwnerType,
  ): Promise<CreateSharedSessionResult>;

  /**
   * Adds a member (collaborative start point) to a shared session.
   *
   * @param sessionId - Session identifier
   * @param member - Member to add
   * @throws {SessionShareError} Typed error codes `not_found`, `expired`, `closed`, `network`…
   */
  joinSharedSession(sessionId: string, member: SharedSessionMemberInput): Promise<void>;

  /**
   * Fetches the current state of a shared session once (one-shot read).
   *
   * @param sessionId - Session identifier
   * @returns Validated shared session, or null if absent
   * @throws {SessionShareError} If the read fails
   */
  fetchSharedSession(sessionId: string): Promise<SharedSession | null>;

  /**
   * Subscribes to a shared session's changes (meta + members live).
   *
   * The handler is called immediately with the current state then on each
   * change. Data is validated via Zod (TS-004).
   *
   * @param sessionId - Session identifier
   * @param onUpdate - Handler called on each change
   * @returns Unsubscribe function
   * @throws {SessionShareError} If the subscription cannot be established
   */
  subscribeToSharedSession(
    sessionId: string,
    onUpdate: SharedSessionUpdateHandler,
  ): SessionShareUnsubscribe;

  /**
   * Updates the recomputed midpoint in the session meta.
   *
   * @param sessionId - Session identifier
   * @param midpoint - Midpoint coordinates
   * @param radius - Zone radius in meters
   * @throws {SessionShareError} If the update fails
   */
  updateMidpoint(sessionId: string, midpoint: Coordinates, radius: number): Promise<void>;

  /**
   * Removes one member (and so its start point, an exact address) from a
   * shared session's roster (GDPR).
   *
   * Best-effort and **never rejects**: the returned promise always resolves,
   * whether the member node was removed, was already missing (idempotent), or
   * could not be removed at all. It is the cleanup step of a join that lost
   * the race against the session's deletion: `JoinSessionUseCase` calls it
   * right after having written `members/{memberId}` and re-read a session
   * that no longer exists, then throws `not_found`. A failed removal must not
   * replace that `not_found` with another error, so the caller awaits this
   * method without a dedicated catch. Implementations must therefore absorb
   * their own errors (e.g. report them to the crash reporter) instead of
   * propagating them.
   *
   * @param sessionId - Session identifier
   * @param memberId - Identifier of the member to remove
   * @returns A promise that always resolves
   */
  removeMember(sessionId: string, memberId: string): Promise<void>;

  /**
   * Deletes the shared session (GDPR — end of session).
   *
   * Idempotent: does not throw if the session no longer exists.
   *
   * @param sessionId - Session identifier
   * @throws {SessionShareError} If removal fails persistently
   */
  deleteSharedSession(sessionId: string): Promise<void>;
}

/**
 * Typed error codes for the session sharing service.
 *
 * - `not_configured`: Firebase not configured (missing native files)
 * - `not_found`: Session not found (invalid/deleted link)
 * - `expired`: Session expired (TTL exceeded)
 * - `closed`: Session closed by the owner
 * - `full`: Session full (5 members reached)
 * - `network`: Network or connection error
 * - `permission_denied`: Security rules deny access
 * - `invalid_data`: Read data invalid (Zod failure)
 * - `unknown`: Unexpected error
 */
export type SessionShareErrorCode =
  | 'not_configured'
  | 'not_found'
  | 'expired'
  | 'closed'
  | 'full'
  | 'network'
  | 'permission_denied'
  | 'invalid_data'
  | 'unknown';

/**
 * Typed business error for the session sharing service.
 *
 * @param message - Human-readable message (not displayed as is)
 * @param code - Typed error code (mapped to an i18n message)
 * @param cause - Optional original error
 */
export class SessionShareError extends Error {
  constructor(
    message: string,
    public readonly code: SessionShareErrorCode,
    public readonly cause?: unknown,
  ) {
    super(message);
    this.name = 'SessionShareError';
  }
}
