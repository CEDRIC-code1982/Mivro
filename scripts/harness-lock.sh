#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# harness-lock.sh — the harness Cedric approved, as a list of hashes.
#
#   bash scripts/harness-lock.sh            verify (a sensor: exit 1 on drift)
#   bash scripts/harness-lock.sh --print    print the lock the tree would produce
#   npm run harness:relock                  refresh it (Cedric, in a terminal)
#
# Covers every harness file present (harness_paths.lockable_files): everything
# outside the product zones — dotfiles, tool configs, package.json and the
# lockfiles — plus the files listed in scripts/harness-protected.txt (JOURNAL
# J-045). Any change to
# them — by Edit, by Bash, by a script the guards did not see — turns this
# sensor red until the lock is refreshed. Refreshing requires an interactive
# terminal and refuses to run inside Claude Code, so the agent cannot approve
# its own harness change (JOURNAL J-029). In CI, a PR that touches the lock also
# needs the `harness-change` label, which only Cedric sets.
# ---------------------------------------------------------------------------
set -uo pipefail

# Never read or write Python bytecode: a .pyc planted in the cache would
# replace the source of a guard or of the stdlib (JOURNAL J-052).
export PYTHONDONTWRITEBYTECODE=1 PYTHONPYCACHEPREFIX=/dev/null/mivro-nopyc

cd "$(git rev-parse --show-toplevel)" || exit 1

LOCK="scripts/harness.lock"

compute() {
  printf '# Harness lock — generated by scripts/harness-lock.sh. Do not edit by hand.\n'
  printf '# Refresh: npm run harness:relock (interactive, human only).\n'
  python3 -I -B -X pycache_prefix=/dev/null/mivro-nopyc scripts/hooks/harness_paths.py --lockable | while IFS= read -r file; do
    printf '%s  %s\n' "$(shasum -a 256 "$file" | cut -d' ' -f1)" "$file"
  done
}

case "${1:-}" in
  --print)
    compute
    exit 0
    ;;
  --update)
    if [ "${CLAUDECODE:-}" = "1" ] || [ ! -t 0 ] || [ ! -t 1 ]; then
      echo "✖ harness:relock must be run by Cedric in an interactive terminal, outside Claude Code." >&2
      exit 1
    fi
    CURRENT="$(compute)"
    if [ -f "$LOCK" ]; then
      diff <(grep -v '^#' "$LOCK") <(printf '%s\n' "$CURRENT" | grep -v '^#') | sed -n 's/^[<>] /  /p' | sort -u -k2 || true
    fi
    printf 'Approve these harness changes? Type RELOCK to confirm: '
    read -r answer
    if [ "$answer" != "RELOCK" ]; then
      echo "Aborted, lock unchanged."
      exit 1
    fi
    printf '%s\n' "$CURRENT" >"$LOCK"
    echo "✔ $LOCK refreshed. Commit it with the harness change it approves."
    exit 0
    ;;
  "") ;;
  *)
    echo "usage: harness-lock.sh [--print|--update]" >&2
    exit 2
    ;;
esac

if [ ! -f "$LOCK" ]; then
  echo "✖ $LOCK is missing: the harness has no approved state to compare against." >&2
  exit 1
fi

EXPECTED="$(grep -v '^#' "$LOCK")"
ACTUAL="$(compute | grep -v '^#')"
if [ "$EXPECTED" = "$ACTUAL" ]; then
  exit 0
fi

echo "✖ The harness differs from the approved lock ($LOCK):"
# No process substitution here: the Bash sandbox of Claude Code denies /dev/fd
# (JOURNAL J-051), and this sensor runs in the agent's shell.
{
  printf '%s\n' "$EXPECTED" | sed 's/^/< /'
  printf '%s\n' "$ACTUAL" | sed 's/^/> /'
} | awk '
  /^< / { old[$3] = $2 }
  /^> / { new[$3] = $2 }
  END {
    for (f in old) if (!(f in new)) print "  removed   " f
    for (f in new) if (!(f in old)) print "  added     " f
    for (f in new) if ((f in old) && old[f] != new[f]) print "  modified  " f
  }' | sort -k2
cat <<'MSG'

A harness file changed (hooks, sensors, lint/test/arch config, CI, package.json
scripts). If the agent made this change, revert it and explain the need to
Cedric instead. If Cedric approves it, he runs `npm run harness:relock` in his
terminal and commits the lock with the change.
MSG
# Harness construction mode (JOURNAL J-055): in a Claude Code session that
# Cedric launched unlocked, the drift above is the work in progress, not a
# tamper. The sensor abstains (named, never counted green) instead of failing,
# so the Stop hook does not halt every turn of the work. Everywhere else it
# stays red: Cedric's terminal and the pre-push (no CLAUDECODE), and CI, where
# MIVRO_NO_ABSTAIN=1 turns any abstention into a failure. Only Cedric's relock
# ends the drift.
#
# The unlock rule of harness_paths.unlocked() is restated here, on purpose: the
# probe must not import any code from scripts/hooks/, the very directory whose
# drift it reports. Three reviews of J-055 made a probe that imported
# harness_paths lie with a file dropped there: a subprocess.py at the root, a
# re.py next to harness_paths, a harness_paths/ package, a forged .pyc. The
# probe below is shell plus an isolated, stdlib-only Python that loads nothing
# from the repository. The project settings are read from the root (the cd
# above), not through CLAUDE_PROJECT_DIR, which the agent's Bash lacks. The two
# copies of the rule are compared by the self-test (section 7).
construction_unlocked() {
  [ "${CLAUDECODE:-}" = "1" ] && [ "${MIVRO_HARNESS_UNLOCK:-}" = "1" ] || return 1
  # An unlock written into a settings `env` block is refused (J-042). The JSON
  # is decoded, not grepped: a key whose final K is a JSON unicode escape
  # (backslash, u, 004B) is the same key to Claude Code. Isolated Python,
  # stdlib only: -I keeps the repository off sys.path, -B -X pycache_prefix
  # reads no bytecode (J-052). Any failure on an existing settings file (not
  # UTF-8, malformed...) fails closed, and the file is named on stderr so a
  # refused construction mode is not a mystery.
  python3 -I -B -X pycache_prefix=/dev/null/mivro-nopyc - \
    "${HOME:-}/.claude/settings.json" "${HOME:-}/.claude/settings.local.json" \
    ".claude/settings.json" ".claude/settings.local.json" <<'PY'
import json
import os
import stat
import sys

for path in sys.argv[1:]:
    if not os.path.exists(path):
        continue
    try:
        # Not a regular file (a FIFO would block open() forever): refused.
        if not stat.S_ISREG(os.stat(path).st_mode):
            raise ValueError("not a regular file")
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
        if "MIVRO_HARNESS_UNLOCK" in text:
            reason = "mentions MIVRO_HARNESS_UNLOCK"
        else:
            data = json.loads(text)
            env = data.get("env") if isinstance(data, dict) else None
            reason = "env block sets the unlock" if isinstance(env, dict) and "MIVRO_HARNESS_UNLOCK" in env else ""
    except Exception as error:  # fail closed on anything, by design
        reason = f"unreadable or malformed ({type(error).__name__})"
    if reason:
        print(f"construction mode refused: {path} {reason}", file=sys.stderr)
        sys.exit(1)
sys.exit(0)
PY
}
if construction_unlocked; then
  echo "harness construction mode (unlocked session): relock pending, CI stays strict"
  exit 3
fi
exit 1
